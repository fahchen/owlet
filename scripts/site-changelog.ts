// Renders CHANGELOG.md into site/changelog.html at deploy time; the page itself is never committed.
// Run with Bun, which runs TypeScript directly, so the deploy needs no install step.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const source = readFileSync(`${root}CHANGELOG.md`, "utf8");

const escape = (text: string): string =>
  text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&#x27;");

// ponytail: only the markdown the changelog uses (inline code); add more when an entry needs it.
const inline = (text: string): string => escape(text).replace(/`([^`]+)`/g, "<code>$1</code>");

const body: string[] = [];
let inList = false;
for (const line of source.split(/\r?\n/)) {
  if (inList && !line.startsWith("- ")) {
    body.push("</ul>");
    inList = false;
  }
  if (line.startsWith("# ") || !line.trim()) continue;
  if (line.startsWith("## ")) {
    const [version, date] = line.slice(3).split(" — ", 2);
    if (body.length) body.push("</section>");
    body.push(`<section class="release"><h2>${inline(version)}</h2>`);
    if (date) body.push(`<p class="date">${inline(date)}</p>`);
  } else if (line.startsWith("### ")) {
    const kind = line.slice(4).trim();
    body.push(`<h3 class="${kind.toLowerCase()}">${inline(kind)}</h3>`);
  } else if (line.startsWith("- ")) {
    if (!inList) {
      body.push("<ul>");
      inList = true;
    }
    body.push(`<li>${inline(line.slice(2))}</li>`);
  } else if (body.length) {
    // Text before the first release is a note for maintainers, not for readers.
    body.push(`<p>${inline(line)}</p>`);
  }
}
if (inList) body.push("</ul>");
body.push("</section>");

const page = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>What’s new in Owlet</title>
<meta name="description" content="Every user-visible change to Owlet, version by version.">
<link rel="canonical" href="https://owlet.fahchen.dev/changelog.html">
<link rel="icon" href="icon.png">
<link rel="apple-touch-icon" href="apple-touch-icon.png">
<!-- Generated by scripts/site-changelog.ts from CHANGELOG.md; edit that file instead. -->
<style>
  :root {
    --ink: oklch(0.22 0.004 260); --dim: oklch(0.50 0.006 260); --line: oklch(0.22 0.004 260 / .1);
    --blue: oklch(0.50 0.15 255); --green: oklch(0.48 0.13 150); --rose: oklch(0.50 0.16 355);
  }
  body { margin: 0; color: var(--ink); background: oklch(1 0 0); font: 16px/1.6 -apple-system, BlinkMacSystemFont, "SF Pro Text", sans-serif; -webkit-font-smoothing: antialiased; }
  a { color: inherit; text-underline-offset: 4px; text-decoration-thickness: 1px; }
  a:hover { color: var(--blue); }
  main { max-width: 620px; margin: 0 auto; padding: 72px 24px 120px; }
  .back { display: inline-flex; align-items: center; gap: 8px; font-size: 15px; text-decoration: none; color: var(--dim); }
  .back img { width: 24px; height: 24px; }
  h1 { font-size: 28px; font-weight: 600; letter-spacing: -.01em; margin: 40px 0 6px; }
  .lede { color: var(--dim); margin: 0 0 56px; }
  .release { padding: 32px 0; border-top: 1px solid var(--line); }
  h2 { font-size: 17px; font-weight: 600; margin: 0; }
  .date { color: var(--dim); font-size: 14px; margin: 2px 0 0; }
  h3 { font-size: 13px; font-weight: 600; margin: 20px 0 6px; }
  h3.added { color: var(--green); } h3.changed { color: var(--blue); } h3.fixed { color: var(--rose); }
  ul { margin: 0; padding-left: 20px; }
  li { margin: 6px 0; }
  .release > p:not(.date) { margin: 16px 0 0; }
  code { font: 14px ui-monospace, "SF Mono", monospace; background: oklch(0.96 0.002 260); border-radius: 4px; padding: 1px 5px; }
</style>
</head>
<body>
<main>
  <a class="back" href="index.html"><img src="icon.png" alt="">Owlet</a>
  <h1>What’s new</h1>
  <p class="lede">Every change you can see, version by version.</p>
  ${body.join("\n")}
</main>
</body>
</html>
`;
writeFileSync(`${root}site/changelog.html`, page);
console.log("wrote site/changelog.html");
